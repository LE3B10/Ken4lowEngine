#pragma once
#include <cstdint>

/// --------------------------------------------------------------
///                         敵のアーキタイプ（役割）
/// --------------------------------------------------------------
/// 展示会向けに、まずは「数値差だけで性格が変わる敵」を増やす。
/// まだ特殊行動（グレネード、回復、盾など）は入れず、
/// FSM + GunAI だけで差別化できるものを優先する。
enum class EnemyArchetype : uint8_t
{
	RifleGrunt,      // 標準的なライフル兵
	SMGFlanker,      // 近距離寄りの回り込み役
	Sniper,          // 遠距離単発高精度
	BurstTrooper,    // 3～4点バースト寄りの中距離兵
	HeavyRifleman,   // 遅い・硬い・やや高火力
	ShotgunRusher,   // 近距離まで詰めてくる突撃兵
	Scout,           // 速い・柔らかい・発見しやすい軽量兵
	Marksman,        // Sniperより軽い中遠距離兵
	Suppressor,      // 命中は甘いが弾幕で圧をかける
	EliteFlanker,    // SMGFlanker の上位版
	HeavySniper,     // 発射は遅いが高火力の重狙撃兵
};

/// --------------------------------------------------------------
///                         敵の行動パターン設定
/// --------------------------------------------------------------
/// Enemy / EnemyStateMachine / EnemyGunAI から共通参照する調整値。
/// 「新しい敵を増やす」ときは、まずこの値を増やして
/// 数値差だけで遊びの幅を出すのが安全。
struct EnemyTuning
{
	// ----------------------------------------------------------
	// 共通
	// ----------------------------------------------------------
	float moveSpeed = 3.0f;      // 移動速度
	float attackRange = 15.0f;   // 攻撃開始距離
	float viewRange = 25.0f;     // 視認距離

	// ----------------------------------------------------------
	// 射撃
	// ----------------------------------------------------------
	float fireInterval = 0.35f;  // 発砲間隔
	int burstMin = 2;            // 1バースト最小弾数
	int burstMax = 4;            // 1バースト最大弾数

	// ----------------------------------------------------------
	// GunAI（距離管理 / ストレイフ）
	// ----------------------------------------------------------
	float preferredMinRatio = 0.35f; // attackRange に対する理想最小距離
	float preferredMaxRatio = 0.65f; // attackRange に対する理想最大距離
	float strafeSpeedMul = 0.75f;    // 横移動速度倍率
	float aimMoveMul = 0.60f;        // エイム中の移動倍率
	float burstMoveMul = 0.20f;      // 射撃中の移動倍率

	// ----------------------------------------------------------
	// 命中ブレ（度）
	// ----------------------------------------------------------
	float spreadNearDeg = 0.5f; // 近距離ブレ
	float spreadFarDeg = 2.8f;  // 遠距離ブレ

	// ----------------------------------------------------------
	// 反応
	// ----------------------------------------------------------
	float reactionDelaySec = 0.25f; // 見つけてから撃ち始めるまでの遅延

	// ----------------------------------------------------------
	// 弾（Enemy::FireAt が使う）
	// ----------------------------------------------------------
	float bulletSpeed = 80.0f;   // 弾速
	float bulletLifeSec = 2.0f;  // 弾寿命
	int   bulletDamage = 1;      // 1発ダメージ

	// ----------------------------------------------------------
	// 耐久
	// ----------------------------------------------------------
	int maxHp = 3;
};
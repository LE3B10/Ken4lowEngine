#include "ScoreManager.h"

#ifdef USE_IMGUI
#include <imgui.h>
#endif // USE_IMGUI

/// -------------------------------------------------------------
///					シングルトンインスタンス取得
/// -------------------------------------------------------------
ScoreManager* ScoreManager::GetInstance()
{
	static ScoreManager instance;
	return &instance;
}

/// -------------------------------------------------------------
///						初期化処理
/// -------------------------------------------------------------
void ScoreManager::Initialize()
{
	// スコアとキル数をリセット
	Reset();
}

/// -------------------------------------------------------------
///						キル数の追加
/// -------------------------------------------------------------
void ScoreManager::AddKill()
{
	// 現状は敵種別に関係なく固定点。敵別スコアを導入する場合はここを分岐点にする。
	++kills_;
	AddScore(100); // 1体倒すごとに100点
}

/// -------------------------------------------------------------
///						スコアのリセット
/// -------------------------------------------------------------
void ScoreManager::Reset()
{
	score_ = 0;
	kills_ = 0;
}

/// -------------------------------------------------------------
///						ImGui描画処理
/// -------------------------------------------------------------
void ScoreManager::DrawImGui() const
{
#ifdef USE_IMGUI
	ImGui::Begin("Score");
	ImGui::Text("Score: %d", score_);
	ImGui::Text("Kills: %d", kills_);
	ImGui::End();
#endif // USE_IMGUI
}
